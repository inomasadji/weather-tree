// Словарь интерфейса и форматирования для двух языков (ru / en).
// Чистый модуль без DOM: используется в model/, state/ и ui/.

export const SUPPORTED_LANGS = ['ru', 'en'];

/**
 * Приводит произвольный код языка к 'ru' или 'en'.
 * @param {string|null|undefined} value
 * @returns {'ru'|'en'}
 */
export function normalizeLang(value) {
  if (typeof value !== 'string') return 'ru';
  return value.trim().toLowerCase().startsWith('en') ? 'en' : 'ru';
}

